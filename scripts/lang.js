// Leemos el idioma guardado en el navegador (por defecto inglés)
let currentLang = localStorage.getItem('mbw_lang') || 'en';

// Función para JS (Alertas, tooltips, etc.)
window.t = function(key) {
    return i18n[currentLang][key] || key; 
};

// Mensaje traducido para alertas / confirmaciones: tmsg('clave', 'texto de respaldo', { n: 3 }) cambia {n} por 3.
window.tmsg = function(key, fallback, vars) {
    let m = (i18n[currentLang] && i18n[currentLang][key]) || (i18n.en && i18n.en[key]) || fallback || key;
    if (vars) Object.keys(vars).forEach(function(k) { m = m.split('{' + k + '}').join(String(vars[k])); });
    return m;
};

// Función que traduce el HTML en tiempo real
window.setLanguage = function(langCode) {
    if (!i18n[langCode]) return;
    
    currentLang = langCode;
    localStorage.setItem('mbw_lang', currentLang); // Guardar preferencia

    // Actualiza el selector del menú Configuration
    const selectEl = document.getElementById('lang-select');
    if (selectEl) selectEl.value = currentLang;

    // Escanear y traducir todos los textos del HTML
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (i18n[currentLang][key]) {
            el.innerHTML = i18n[currentLang][key]; // Reemplaza el texto (soporta <br>)
        }
    });

    // Escanear y traducir los "placeholder" de los inputs
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (i18n[currentLang][key]) {
            el.placeholder = i18n[currentLang][key];
        }
    });

    // Escanear y traducir los títulos/tooltips (title="")
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (i18n[currentLang][key]) {
            el.title = i18n[currentLang][key];
        }
    });

    // El chat privado pinta textos por código (Hoy, Visto, Desconectado...): se refrescan
    if (typeof window.dmOnLanguageChanged === 'function') window.dmOnLanguageChanged();

    // El Mob Browser pinta su panel por código: también se refresca
    if (typeof window.mobEditorOnLanguageChanged === 'function') window.mobEditorOnLanguageChanged();

    // El inventario del jugador pinta sus tooltips y el botón de la ventana por código: también se refrescan
    if (typeof window.playerInvOnLanguageChanged === 'function') window.playerInvOnLanguageChanged();

    // Marcadores / vehículos pintan textos por código: también se refrescan
    if (typeof window.mbwExtrasOnLanguageChanged === 'function') window.mbwExtrasOnLanguageChanged();
    try { window.dispatchEvent(new Event('mbw-lang-changed')); } catch (e) { /* nada */ }

    // La galería de skins pinta sus textos por código
    if (typeof window.skinGalleryOnLanguageChanged === 'function') window.skinGalleryOnLanguageChanged();

    // El botón "pegar solo sobre…" y la burbuja de chat también pintan textos por código
    if (typeof window.pasteFilterOnLanguageChanged === 'function') window.pasteFilterOnLanguageChanged();
    if (window.mbwChatHead && typeof window.mbwChatHead.refresh === 'function') window.mbwChatHead.refresh();
    if (typeof window.miniChatOnLanguageChanged === 'function') window.miniChatOnLanguageChanged();

    // Atajos de teclado, lista de herramientas, datos del mundo y mobs recientes también se pintan por código
    if (typeof window.uiOnLanguageChanged === 'function') window.uiOnLanguageChanged();
    // El asistente "Create Server" (scripts/server-wizard.js)
    if (typeof window.serverWizardOnLanguageChanged === 'function') window.serverWizardOnLanguageChanged();
    if (typeof window.topAreaOnLanguageChanged === 'function') window.topAreaOnLanguageChanged();
    if (typeof window.mpLiveOnLanguageChanged === 'function') window.mpLiveOnLanguageChanged();
    if (typeof window.aspectOnLanguageChanged === 'function') window.aspectOnLanguageChanged();
};

